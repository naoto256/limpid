#[cfg(test)]
mod tests {
    use super::*;
    use crate::header::parse_str;

    fn mk(kind: SnippetKind, path: &str, content: &str) -> SnippetHeader {
        parse_str(std::path::Path::new(path), kind, content).unwrap()
    }

    #[test]
    fn contains_call_boundary_check() {
        assert!(contains_call("workspace.x = parse_kv(y)", "parse_kv"));
        assert!(!contains_call("workspace.x = parse_kv2(y)", "parse_kv"));
        assert!(!contains_call("workspace.x = my_parse_kv(y)", "parse_kv"));
        assert!(contains_call("parse_kv(y)", "parse_kv"));
    }

    #[test]
    fn used_by_excludes_header_and_comments() {
        // Defining file: proto_num function.
        let def_file = "/repo/packaging/snippets/functions/proto_num.limpid";
        let def_content = "\
// Summary:     IANA proto
// Signature:   proto_num(name) → Int | null
// Test corpus: unit (registry)

def function proto_num(name) {
    switch lower(name) {
        \"tcp\" { 6 }
        default { null }
    }
}
";
        let def_header = mk(SnippetKind::Function, def_file, def_content);

        // Caller in the header — must NOT count (headers don't call).
        let caller_header_only = mk(
            SnippetKind::Parser,
            "/repo/packaging/snippets/parsers/parse_x.limpid",
            "\
// Summary:     Look, proto_num(6) in the header
// Reads:       ingress (raw wire) — X
// Writes:      workspace.lsis.* — 4001
// Category:    Network firewall / IPS
// Test corpus: real (x)

def process x {}
",
        );

        // Caller in the body — must count.
        let caller_body = mk(
            SnippetKind::Parser,
            "/repo/packaging/snippets/parsers/parse_y.limpid",
            "\
// Summary:     Y
// Reads:       ingress (raw wire) — Y
// Writes:      workspace.lsis.* — 4001
// Category:    Network firewall / IPS
// Test corpus: real (y)

def process y {
    workspace.lsis.proto = proto_num(workspace.raw.proto)
}
",
        );

        // Comment-only body reference — must NOT count.
        let caller_comment = mk(
            SnippetKind::Parser,
            "/repo/packaging/snippets/parsers/parse_z.limpid",
            "\
// Summary:     Z
// Reads:       ingress (raw wire) — Z
// Writes:      workspace.lsis.* — 4001
// Category:    Network firewall / IPS
// Test corpus: real (z)

def process z {
    // proto_num(x) would work here but we compute inline instead
    workspace.lsis.proto = 6
}
",
        );

        let all = vec![def_header.clone(), caller_header_only, caller_body.clone(), caller_comment];
        let callers = derive_used_by("proto_num", &def_header.file, &all);
        assert_eq!(callers, vec![caller_body.file.clone()]);
    }

    #[test]
    fn used_by_excludes_defining_file_declaration_line_but_would_count_body_use() {
        // If the function references itself elsewhere in its own file
        // (banned by the analyzer but possible to text-match), only
        // the declaration line is skipped — other lines still count.
        // Analyzer bans recursion, so in practice this stays 0, but
        // the guardrail should be surgical.
        let def_content = "\
// Summary:     Self-caller
// Signature:   selfy(x) → Int
// Test corpus: unit (docs)

def function selfy(x) {
    selfy(x - 1)
}
";
        let def_file = "/repo/packaging/snippets/functions/selfy.limpid";
        let def = mk(SnippetKind::Function, def_file, def_content);
        // The declaration line `def function selfy(` is skipped; the
        // recursion in the body still counts. So Used-by lists the
        // defining file itself.
        let callers = derive_used_by("selfy", &def.file, &[def.clone()]);
        assert_eq!(callers, vec![def.file.clone()]);
    }

    #[test]
    fn parsers_table_grouped_by_category() {
        let a = mk(
            SnippetKind::Parser,
            "/r/packaging/snippets/parsers/parse_a.limpid",
            "\
// Summary:     A summary
// Reads:       ingress (raw wire) — A
// Writes:      workspace.lsis.* — 4001
// Category:    Transport
// Test corpus: real (a)
",
        );
        let b = mk(
            SnippetKind::Parser,
            "/r/packaging/snippets/parsers/parse_b.limpid",
            "\
// Summary:     B summary
// Reads:       ingress (raw wire) — B
// Writes:      workspace.lsis.* — 4001
// Category:    Network firewall / IPS
// Test corpus: real (b)
",
        );
        let out = render_parsers_table(&[a, b]);
        // Transport appears before Network firewall in CATEGORIES.
        let t = out.find("**Transport**").unwrap();
        let n = out.find("**Network firewall / IPS**").unwrap();
        assert!(t < n);
        assert!(out.contains("parse_a.limpid"));
        assert!(out.contains("parse_b.limpid"));
    }

    #[test]
    fn composers_table_prints_writes_first_token() {
        let c = mk(
            SnippetKind::Composer,
            "/r/packaging/snippets/composers/compose_ocsf.limpid",
            "\
// Summary:     Renders LSIS to OCSF 1.3.0
// Reads:       workspace.lsis.* (LSIS)
//                .class_uid (required, Int) — dispatch discriminator
// Writes:      workspace.lsis.ocsf — OCSF 1.3.0 JSON string
// Test corpus: real (r)
",
        );
        let out = render_composers_table(&[c]);
        assert!(out.contains("`workspace.lsis.ocsf`"));
        assert!(out.contains("Renders LSIS to OCSF 1.3.0"));
    }

    #[test]
    fn replace_marked_region_basic() {
        let input = "prefix\n<!-- BEGIN: foo -->\nold\n<!-- END: foo -->\nsuffix\n";
        let out = replace_marked_region(input, "foo", "new content").unwrap();
        assert!(out.contains("<!-- BEGIN: foo -->\nnew content\n<!-- END: foo -->"));
        assert!(out.contains("prefix"));
        assert!(out.contains("suffix"));
    }

    #[test]
    fn replace_marked_region_missing_begin_errors() {
        assert!(replace_marked_region("no markers", "foo", "x").is_err());
    }
}
